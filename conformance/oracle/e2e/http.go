package main

// The -http mode of the e2e oracle: the WHOLE HTTP response grpc-gateway
// writes for one request, when the backend behind it answers a FIXED message
// or a FIXED error.
//
// The earlier mode (main.go) stops at the gRPC request the backend received,
// so it can only prove the request half. This one puts a real net/http server
// in front of the same generated handlers, makes the in-process gRPC backend
// answer whatever the case says, and records status, headers in order, body
// bytes and trailers — everything an HTTP client sees. abada replays the same
// cases against its own Gateway with the same backend behaviour
// (crates/abada/tests/e2e.rs).
//
//	e2e -http <descriptor set> <source> < cases.json > vectors.json

