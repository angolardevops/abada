// backendSpec is what the fake gRPC server does for one case. Exactly one of
// Reply and Error decides the outcome; both metadata sets are sent either way,
// because the generated handler captures them with grpc.Header/grpc.Trailer
// before it looks at the error.
type backendSpec struct {
	// Reply is the response message in prototext, against the called method's
	// output type. Empty means the empty message (not "no reply").
	Reply string `json:"reply,omitempty"`
	// Error, when set, makes the RPC fail instead.
	Error *errorSpec `json:"error,omitempty"`
	// HeaderMD and TrailerMD are sent with grpc.SetHeader/grpc.SetTrailer.
	HeaderMD  [][2]string `json:"header_md,omitempty"`
	TrailerMD [][2]string `json:"trailer_md,omitempty"`
}

type errorSpec struct {
	Code    int32     `json:"code"`
	Message string    `json:"message"`
	Details []anyCase `json:"details,omitempty"`
}

type anyCase struct {
	TypeURL  string `json:"type_url,omitempty"`
	ValueHex string `json:"value_hex,omitempty"`
}

type httpCase struct {
	Name    string      `json:"name"`
	Mux     string      `json:"mux,omitempty"`
	Method  string      `json:"method"`
	Target  string      `json:"target"`
	Headers [][2]string `json:"headers,omitempty"`
	Body    string      `json:"body,omitempty"`
	Backend backendSpec `json:"backend"`
}

type httpCases struct {
	Cases []httpCase `json:"cases"`
}

// httpWire is what reaches an HTTP/1.1 client. Same normalisation as the
// errors oracle (conformance/oracle/errors.go), for the same reasons.
type httpWire struct {
	Status   int         `json:"status"`
	Headers  [][2]string `json:"headers"`
	Body     string      `json:"body,omitempty"`
	BodyHex  string      `json:"body_hex,omitempty"`
	Trailers [][2]string `json:"trailers,omitempty"`
	// Closed is true when the server wrote nothing at all: the generated
	// handler panicked and net/http dropped the connection.
	Closed bool `json:"closed,omitempty"`
}

type httpVector struct {
	httpCase
	// RPC and Request are what the backend received, so the request half stays
	// pinned in the same vector as the response half.
	RPC     string `json:"rpc,omitempty"`
	Request string `json:"request,omitempty"`
	// Registered says, per detail, whether this binary resolves its type URL.
	Registered []bool `json:"registered,omitempty"`
	// Response is kept under its own key, not embedded: httpCase already has
	// `headers` and `body` (the REQUEST's), and encoding/json drops both
	// sides of a name collision between two embedded structs — silently.
	Response httpWire `json:"response"`
}

type httpVectors struct {
	Generator string       `json:"generator"`
	Source    string       `json:"source"`
	Note      string       `json:"note"`
	Vectors   []httpVector `json:"vectors"`
	Dropped   []string     `json:"dropped_nondeterministic,omitempty"`
}

const httpNote = "The whole HTTP/1.1 response of a real net/http server in front of handlers generated by " +
	"protoc-gen-grpc-gateway (allow_patch_feature=true, repeated_path_param_separator=csv), over a real " +
	"gRPC connection (bufconn) to a backend that answers what the case says. Headers exclude date, " +
	"content-length, connection and transfer-encoding, which net/http adds for framing; names are " +
	"lower-cased and the list sorted by name, because grpc-gateway writes metadata in Go map order. " +
	"protojson's random space after a comma (internal/detrand) is removed. body is set when the bytes " +
	"are valid UTF-8, body_hex otherwise. closed=true means the generated handler panicked (a nil " +
	"intermediate message in a nested response_body) and net/http closed the connection with no reply."

// fixed is the backend behaviour for the case being run. One case runs at a
// time, so a single guarded slot is enough and the answer stays a fixed
// function of the case.
type fixed struct {
	mu   sync.Mutex
	spec backendSpec
	got  []received
}

func (f *fixed) set(spec backendSpec) {
	f.mu.Lock()
	f.spec, f.got = spec, nil
	f.mu.Unlock()
}

func (f *fixed) take() []received {
	f.mu.Lock()
	defer f.mu.Unlock()
	got := f.got
	f.got = nil
	return got
}

func (f *fixed) handle(_ any, stream grpc.ServerStream) error {
	rpc, _ := grpc.MethodFromServerStream(stream)
	var msg []byte
	if err := stream.RecvMsg(&msg); err != nil {
		return err
	}
	f.mu.Lock()
	spec := f.spec
	f.got = append(f.got, received{rpc: rpc, msg: msg})
	f.mu.Unlock()

	if len(spec.HeaderMD) > 0 {
		if err := stream.SetHeader(mdPairs(spec.HeaderMD)); err != nil {
			return err
		}
	}
	if len(spec.TrailerMD) > 0 {
		stream.SetTrailer(mdPairs(spec.TrailerMD))
	}
	if spec.Error != nil {
		return statusOfSpec(*spec.Error)
	}
	out, err := replyBytes(rpc, spec.Reply)
	if err != nil {
		return err
	}
	return stream.SendMsg(&out)
}

func mdPairs(pairs [][2]string) metadata.MD {
	md := metadata.MD{}
	for _, p := range pairs {
		md.Append(p[0], p[1])
	}
	return md
}

// statusOfSpec builds the error the backend returns. Details go in through the
// status proto, so grpc-go writes them into grpc-status-details-bin and the
// client reads them back through internal/status.NewWithProto — which, when
// the codes agree, uses the decoded proto whole, details included.
func statusOfSpec(e errorSpec) error {
	sp := &spb.Status{Code: e.Code, Message: e.Message}
	for _, d := range e.Details {
		value, err := hex.DecodeString(d.ValueHex)
		if err != nil {
			fail("value_hex: %v", err)
		}
		sp.Details = append(sp.Details, &anypb.Any{TypeUrl: d.TypeURL, Value: value})
	}
	return status.FromProto(sp).Err()
}

// replyBytes encodes the case's prototext against the called method's output
// message, through the global registry — the generated Go type when the binary
// links one, which it does for every contract the oracle compiles.
func replyBytes(rpc, text string) ([]byte, error) {
	md, err := methodOf(rpc)
	if err != nil {
		return nil, err
	}
	mt, err := protoregistry.GlobalTypes.FindMessageByName(md.Output().FullName())
	if err != nil {
		return nil, err
	}
	m := mt.New().Interface()
	if text != "" {
		if err := (prototext.UnmarshalOptions{AllowPartial: true}).Unmarshal([]byte(text), m); err != nil {
			return nil, fmt.Errorf("reply %q: %w", text, err)
		}
	}
	return proto.MarshalOptions{Deterministic: true, AllowPartial: true}.Marshal(m)
}

func methodOf(rpc string) (protoreflect.MethodDescriptor, error) {
	name := strings.TrimPrefix(rpc, "/")
	svc, method, ok := strings.Cut(name, "/")
	if !ok {
		return nil, fmt.Errorf("rpc %q", rpc)
	}
	d, err := protoregistry.GlobalFiles.FindDescriptorByName(protoreflect.FullName(svc))
	if err != nil {
		return nil, err
	}
	sd, ok := d.(protoreflect.ServiceDescriptor)
	if !ok {
		return nil, fmt.Errorf("%s is not a service", svc)
	}
	md := sd.Methods().ByName(protoreflect.Name(method))
	if md == nil {
		return nil, fmt.Errorf("no method %s in %s", method, svc)
	}
	return md, nil
}

func runHTTP(setPath, source string) {
	services := servicesOf(setPath)
	var c httpCases
	if err := json.NewDecoder(os.Stdin).Decode(&c); err != nil {
		fail("decode cases: %v", err)
	}

	f := &fixed{}
	conn := dialBackend(f.handle)
	muxes := newMuxes(services, conn)

	out := httpVectors{Generator: os.Getenv("ABADA_GENERATOR"), Source: source, Note: httpNote}
	seen := map[string]bool{}
	for _, hc := range c.Cases {
		if seen[hc.Name] {
			fail("case %s: duplicate name", hc.Name)
		}
		seen[hc.Name] = true
		mux, ok := muxes[hc.Mux]
		if !ok {
			fail("case %s: unknown mux %q", hc.Name, hc.Mux)
		}
		first := runHTTPCase(mux, f, hc)
		stable := true
		for i := 0; i < 8 && stable; i++ {
			stable = sameVector(first, runHTTPCase(mux, f, hc))
		}
		if !stable {
			out.Dropped = append(out.Dropped, hc.Name)
			continue
		}
		for _, d := range hc.Backend.errorDetails() {
			_, rerr := protoregistry.GlobalTypes.FindMessageByURL(d.TypeURL)
			first.Registered = append(first.Registered, rerr == nil)
		}
		out.Vectors = append(out.Vectors, first)
	}
	enc := json.NewEncoder(os.Stdout)
	enc.SetIndent("", "  ")
	enc.SetEscapeHTML(false)
	if err := enc.Encode(out); err != nil {
		fail("encode: %v", err)
	}
}

func (b backendSpec) errorDetails() []anyCase {
	if b.Error == nil {
		return nil
	}
	return b.Error.Details
}

func runHTTPCase(mux *runtime.ServeMux, f *fixed, hc httpCase) httpVector {
	f.set(hc.Backend)
	v := httpVector{httpCase: hc}
	v.Response = exchangeRaw(mux, hc)
	if got := f.take(); len(got) == 1 {
		v.RPC = got[0].rpc
		v.Request = base64.StdEncoding.EncodeToString(deterministicRequest(hc.Name, got[0]))
	} else if len(got) > 1 {
		fail("case %s: %d calls", hc.Name, len(got))
	}
	return v
}

// deterministicRequest re-encodes what the backend received, so a vector does
// not depend on the field order the gateway happened to write.
func deterministicRequest(name string, r received) []byte {
	md, err := methodOf(r.rpc)
	if err != nil {
		fail("case %s: %v", name, err)
	}
	mt, err := protoregistry.GlobalTypes.FindMessageByName(md.Input().FullName())
	if err != nil {
		fail("case %s: %v", name, err)
	}
	m := mt.New().Interface()
	if err := (proto.UnmarshalOptions{AllowPartial: true}).Unmarshal(r.msg, m); err != nil {
		fail("case %s: request does not decode: %v", name, err)
	}
	bin, err := proto.MarshalOptions{Deterministic: true, AllowPartial: true}.Marshal(m)
	if err != nil {
		fail("case %s: %v", name, err)
	}
	return bin
}

// exchangeRaw writes one raw HTTP/1.1 request and parses the raw answer, so
// nothing a client library normalises is hidden — the same method
// conformance/oracle/errors.go uses, with a request body added.
func exchangeRaw(h http.Handler, hc httpCase) httpWire {
	srv := httptest.NewUnstartedServer(h)
	srv.Config.ErrorLog = log.New(io.Discard, "", 0)
	srv.Start()
	defer srv.Close()
	conn, err := net.Dial("tcp", srv.Listener.Addr().String())
	if err != nil {
		fail("case %s: dial: %v", hc.Name, err)
	}
	defer conn.Close()
	var req bytes.Buffer
	fmt.Fprintf(&req, "%s %s HTTP/1.1\r\nHost: abada\r\n", hc.Method, hc.Target)
	for _, h := range hc.Headers {
		fmt.Fprintf(&req, "%s: %s\r\n", h[0], h[1])
	}
	fmt.Fprintf(&req, "Content-Length: %d\r\nConnection: close\r\n\r\n%s", len(hc.Body), hc.Body)
	if _, err := conn.Write(req.Bytes()); err != nil {
		fail("case %s: write: %v", hc.Name, err)
	}
	raw, err := io.ReadAll(conn)
	if err != nil {
		fail("case %s: read: %v", hc.Name, err)
	}
	return parseHTTPWire(raw, hc.Name)
}

var httpFraming = map[string]bool{"date": true, "content-length": true, "connection": true, "transfer-encoding": true}

func httpHeaderLines(block []byte, name string) (all [][2]string, kept [][2]string) {
	for _, line := range strings.Split(string(block), "\r\n") {
		if line == "" {
			continue
		}
		k, v, ok := strings.Cut(line, ":")
		if !ok {
			fail("case %s: header line %q", name, line)
		}
		kv := [2]string{strings.ToLower(k), strings.TrimPrefix(v, " ")}
		all = append(all, kv)
		if !httpFraming[kv[0]] {
			kept = append(kept, kv)
		}
	}
	// grpc-gateway writes metadata by walking a Go map, so only the set is a
	// fixed expectation. Values of one name keep their order (Add appends).
	sort.SliceStable(kept, func(i, j int) bool { return kept[i][0] < kept[j][0] })
	return all, kept
}

func parseHTTPWire(raw []byte, name string) httpWire {
	var w httpWire
	if len(raw) == 0 {
		w.Closed = true
		w.Headers = [][2]string{}
		return w
	}
	head, rest, ok := bytes.Cut(raw, []byte("\r\n\r\n"))
	if !ok {
		fail("case %s: no end of headers in %q", name, raw)
	}
	statusLine, headerBlock, _ := bytes.Cut(head, []byte("\r\n"))
	fields := strings.Fields(string(statusLine))
	if len(fields) < 2 {
		fail("case %s: status line %q", name, statusLine)
	}
	w.Status, _ = strconv.Atoi(fields[1])
	all, kept := httpHeaderLines(headerBlock, name)
	w.Headers = kept
	if w.Headers == nil {
		w.Headers = [][2]string{}
	}
	chunked := false
	for _, kv := range all {
		if kv[0] == "transfer-encoding" && kv[1] == "chunked" {
			chunked = true
		}
	}
	body := rest
	if chunked {
		body = nil
		r := bufio.NewReader(bytes.NewReader(rest))
		for {
			line, err := r.ReadString('\n')
			if err != nil {
				fail("case %s: chunk size: %v", name, err)
			}
			n, err := strconv.ParseInt(strings.TrimSpace(line), 16, 64)
			if err != nil {
				fail("case %s: chunk size %q", name, line)
			}
			if n == 0 {
				tail, _ := io.ReadAll(r)
				_, w.Trailers = httpHeaderLines(tail, name)
				break
			}
			chunk := make([]byte, n+2)
			if _, err := io.ReadFull(r, chunk); err != nil {
				fail("case %s: chunk: %v", name, err)
			}
			body = append(body, chunk[:n]...)
		}
	}
	if isPrintableJSON(body) {
		w.Body = withoutSpaces(string(body))
	} else {
		w.BodyHex = hex.EncodeToString(body)
	}
	return w
}

// isPrintableJSON keeps the readable field for bodies that are valid UTF-8; a
// google.api.HttpBody carries arbitrary bytes, which go to body_hex instead.
func isPrintableJSON(b []byte) bool {
	if len(b) == 0 {
		return true
	}
	if !utf8.Valid(b) {
		return false
	}
	for _, c := range b {
		if c < 0x20 && c != '\n' && c != '\t' && c != '\r' {
			return false
		}
	}
	return true
}

// withoutSpaces removes the whitespace protojson adds outside strings, value
// by value. A body that is not a JSON object is left alone: HttpBody data and
// the fallback constants are written byte for byte.
func withoutSpaces(body string) string {
	if !strings.HasPrefix(body, "{") {
		return body
	}
	var out strings.Builder
	for len(body) > 0 {
		end := topLevelEnd(body)
		value := body[:end]
		body = body[end:]
		if !strings.HasPrefix(value, "{") {
			out.WriteString(value)
			continue
		}
		inString, escaped := false, false
		for i := 0; i < len(value); i++ {
			c := value[i]
			switch {
			case inString && escaped:
				escaped = false
			case inString && c == '\\':
				escaped = true
			case c == '"':
				inString = !inString
			case !inString && c == ' ':
				continue
			}
			out.WriteByte(c)
		}
	}
	return out.String()
}

func sameVector(a, b httpVector) bool {
	x, _ := json.Marshal(a)
	y, _ := json.Marshal(b)
	return bytes.Equal(x, y)
}
